import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const wordsPath = path.join(projectRoot, 'src', 'data', 'words.ts');
const publicDataPath = path.join(projectRoot, 'public', 'data');
const wordDataPath = path.join(publicDataPath, 'words');
const summaryPath = path.join(projectRoot, 'src', 'data', 'site-summary.ts');

const popularWords = ['stor', 'snabb', 'varm', 'glad', 'ljus', 'hög', 'ung', 'full', 'öppen', 'lätt'];
const homepageWords = [...popularWords, 'tidig', 'rätt', 'rik', 'dag'];

function readWords() {
  const source = fs.readFileSync(wordsPath, 'utf-8');
  const jsonStart = source.indexOf('{');
  const jsonEnd = source.lastIndexOf('}');

  if (jsonStart === -1 || jsonEnd === -1 || jsonEnd < jsonStart) {
    throw new Error('Could not find generated word data in src/data/words.ts.');
  }

  return JSON.parse(source.slice(jsonStart, jsonEnd + 1));
}

function shardName(word) {
  const firstCharacter = word.charAt(0).toLocaleLowerCase('sv-SE');

  if (firstCharacter === 'å') return 'aa';
  if (firstCharacter === 'ä') return 'ae';
  if (firstCharacter === 'ö') return 'oe';
  if (/^[a-z]$/.test(firstCharacter)) return firstCharacter;
  return 'other';
}

function generateClientData() {
  const words = readWords();
  const wordNames = Object.keys(words).sort((left, right) => left.localeCompare(right, 'sv'));
  const shards = {};

  for (const word of wordNames) {
    const name = shardName(word);
    shards[name] ??= {};
    shards[name][word] = words[word];
  }

  fs.rmSync(publicDataPath, { recursive: true, force: true });
  fs.mkdirSync(wordDataPath, { recursive: true });

  fs.writeFileSync(
    path.join(publicDataPath, 'search-index.json'),
    JSON.stringify(wordNames),
    'utf-8',
  );

  for (const [name, entries] of Object.entries(shards)) {
    fs.writeFileSync(
      path.join(wordDataPath, name + '.json'),
      JSON.stringify(entries),
      'utf-8',
    );
  }

  const featuredOpposites = {};
  for (const word of homepageWords) {
    const opposite = words[word]?.opposite;
    if (!opposite) throw new Error('Missing featured word: ' + word);
    featuredOpposites[word] = opposite;
  }

  const summary = [
    '// This file is generated by generate-client-data.js.',
    'export const wordCount = ' + wordNames.length,
    'export const pairCount = ' + Math.floor(wordNames.length / 2),
    'export const featuredOpposites = ' + JSON.stringify(featuredOpposites, null, 2) + ' as const',
    '',
  ].join('\n');

  fs.writeFileSync(summaryPath, summary, 'utf-8');

  console.log(
    'Generated a ' + wordNames.length + '-word search index and '
      + Object.keys(shards).length + ' letter-based data files.',
  );
}

generateClientData();


function capitalise(word) {
  return word.charAt(0).toLocaleUpperCase('sv') + word.slice(1);
}

function makePair(value, kind) {
  const [a, b] = value.split('|');
  if (kind === 'descriptor') {
    return {
      a,
      b,
      description: `${capitalise(a)} och ${b} beskriver motsatta egenskaper eller tillstånd i den här betydelsen.`,
      examples: [
        `I jämförelsen beskrevs det ena som ${a} och det andra som ${b}.`,
        `Skillnaden mellan något ${a} och något ${b} blev tydlig.`,
      ],
    };
  }
  if (kind === 'verb') {
    return {
      a,
      b,
      description: `${capitalise(a)} och ${b} beskriver motsatta handlingar i det här sammanhanget.`,
      examples: [
        `Orden ${a} och ${b} beskriver två motsatta handlingar.`,
        `Instruktionen skiljer mellan att ${a} och att ${b}.`,
      ],
    };
  }
  return {
    a,
    b,
    description: `${capitalise(a)} och ${b} används som motsatta eller tydligt kontrasterande begrepp i det här sammanhanget.`,
    examples: [
      `Texten jämför ordet ”${a}” med ”${b}”.`,
      `Skillnaden mellan ”${a}” och ”${b}” blev tydlig i exemplet.`,
    ],
  };
}

